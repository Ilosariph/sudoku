"""Trains the scanner's digit classifier (a small MLP) with numpy only and
writes public/js/digit-model.js with int8-quantized weights.

Usage: python3 train.py <train.bin> <val.bin>
Each record is 785 bytes: label (1-9) followed by a 28x28 input (0-255).
"""
import base64
import json
import sys
from pathlib import Path

import numpy as np

SIZES = [784, 128, 9]
EPOCHS = 30
BATCH = 256
LR = 2e-3
OUT = Path(__file__).resolve().parents[2] / 'public' / 'js' / 'digit-model.js'

rng = np.random.default_rng(0)


def load(path):
    d = np.fromfile(path, dtype=np.uint8).reshape(-1, 785)
    return d[:, 1:].astype(np.float32) / 255, d[:, 0].astype(np.int64) - 1


def shift(x):
    """Random ±1 px translation of each 28x28 image."""
    img = x.reshape(-1, 28, 28)
    out = np.empty_like(img)
    dx = rng.integers(-1, 2, len(img))
    dy = rng.integers(-1, 2, len(img))
    for sx in (-1, 0, 1):
        for sy in (-1, 0, 1):
            m = (dx == sx) & (dy == sy)
            out[m] = np.roll(img[m], (sy, sx), axis=(1, 2))
    return out.reshape(len(x), -1)


def forward(params, x):
    acts = [x]
    for k, (w, b) in enumerate(params):
        x = x @ w.T + b
        if k < len(params) - 1:
            x = np.maximum(x, 0)
        acts.append(x)
    return acts


def accuracy(params, x, y):
    return float((forward(params, x)[-1].argmax(1) == y).mean())


def quantize(params):
    q = []
    for w, b in params:
        scale = float(np.abs(w).max() / 127)
        q.append((np.round(w / scale).astype(np.int8), scale, b))
    return q


def dequantize(q):
    return [(w.astype(np.float32) * s, b) for w, s, b in q]


def main(train_path, val_path):
    xt, yt = load(train_path)
    xv, yv = load(val_path)
    print(f'train {len(xt)}, val {len(xv)}')

    params = []
    for i, o in zip(SIZES, SIZES[1:]):
        params.append((rng.normal(0, np.sqrt(2 / i), (o, i)).astype(np.float32), np.zeros(o, np.float32)))
    m = [(np.zeros_like(w), np.zeros_like(b)) for w, b in params]
    v = [(np.zeros_like(w), np.zeros_like(b)) for w, b in params]
    step = 0

    for epoch in range(EPOCHS):
        lr = LR * 0.5 * (1 + np.cos(np.pi * epoch / EPOCHS))
        order = rng.permutation(len(xt))
        for s in range(0, len(order), BATCH):
            idx = order[s:s + BATCH]
            x, y = shift(xt[idx]), yt[idx]
            acts = forward(params, x)
            logits = acts[-1]
            p = np.exp(logits - logits.max(1, keepdims=True))
            p /= p.sum(1, keepdims=True)
            p[np.arange(len(y)), y] -= 1
            grad = p / len(y)
            step += 1
            for k in range(len(params) - 1, -1, -1):
                w, b = params[k]
                gw = grad.T @ acts[k] + 1e-4 * w
                gb = grad.sum(0)
                if k:
                    grad = (grad @ w) * (acts[k] > 0)
                new = []
                for j, (g, prm) in enumerate(((gw, w), (gb, b))):
                    m[k][j][...] = 0.9 * m[k][j] + 0.1 * g
                    v[k][j][...] = 0.999 * v[k][j] + 0.001 * g * g
                    mh = m[k][j] / (1 - 0.9 ** step)
                    vh = v[k][j] / (1 - 0.999 ** step)
                    new.append(prm - lr * mh / (np.sqrt(vh) + 1e-8))
                params[k] = tuple(new)
        print(f'epoch {epoch + 1}: train {accuracy(params, xt[:20000], yt[:20000]):.4f} val {accuracy(params, xv, yv):.4f}')

    q = quantize(params)
    print(f'quantized val {accuracy(dequantize(q), xv, yv):.4f}')
    layers = [{
        'in': int(w.shape[1]),
        'out': int(w.shape[0]),
        'scale': scale,
        'w': base64.b64encode(w.tobytes()).decode(),
        'b': [round(float(x), 5) for x in b],
    } for w, scale, b in q]
    OUT.write_text(
        '// Generated by tools/digit-model/train.py. Do not edit by hand.\n'
        '// MLP for printed digits 1-9: int8 weights (row-major [out][in]) times scale.\n'
        f'export const MODEL = {json.dumps({"layers": layers})};\n'
    )
    print(f'wrote {OUT} ({OUT.stat().st_size // 1024} KB)')


if __name__ == '__main__':
    main(*sys.argv[1:3])
